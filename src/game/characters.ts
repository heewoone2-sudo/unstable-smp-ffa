function buildLoadout(
  ids: [WeaponSlotId, WeaponSlotId, WeaponSlotId, WeaponSlotId, WeaponSlotId, WeaponSlotId]
): CharacterProfile['loadout'] {
  return ids.map((id, idx) => {
    const item = ITEM_CATALOG[id];
    return {
      ...item,
      role: item.role ?? item.shortName,
      keyHint: String(idx + 1),
    };
  }) as CharacterProfile['loadout'];
}

