export function isRangedWeapon(slot: WeaponSlotId): boolean {
  return slot === 'bow' || slot === 'crossbow';
}

export function hasRangedBowLoadout(
  loadout: readonly (LoadoutItemConfig | null)[]
): boolean {
  return loadout.some((item) => item !== null && isRangedWeapon(item.id));
}

export function hasDoubleJumpLoadout(
  loadout: readonly (LoadoutItemConfig | null)[]
): boolean {
  return loadout.some(
    (item) => item !== null && (item.id === 'bow' || item.id === 'crossbow' || item.id === 'mace')
  );
}
